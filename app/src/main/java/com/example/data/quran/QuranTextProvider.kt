object QuranTextProvider {

    // Removes Arabic diacritics for ultra-fast, accurate search
    fun normalizeArabic(text: String): String {
        return text
            .replace("[\\u064B-\\u065F\\u0670\\u06D6-\\u06ED]".toRegex(), "")
            .replace("أ", "ا")
            .replace("إ", "ا")
            .replace("آ", "ا")
            .replace("ة", "ه")
            .replace("ى", "ي")
            .replace("ؤ", "و")
            .replace("ئ", "ي")
            .replace("ـ", "")
            .trim()
    }

    fun getAyahsForSurah(surahNumber: Int): List<Ayah> {
        val staticAyahs = surahAyahsMap[surahNumber]
        if (staticAyahs != null && staticAyahs.isNotEmpty()) {
            return staticAyahs
        }
        return generateAyahsForSurah(surahNumber)
    }

    fun searchQuran(query: String): List<AyahSearchResult> {
        if (query.isBlank()) return emptyList()
        val normalizedQuery = normalizeArabic(query).lowercase()
        val results = mutableListOf<AyahSearchResult>()

        for (surah in QuranDataProvider.surahs) {
            val ayahs = getAyahsForSurah(surah.number)
            for (ayah in ayahs) {
                val normalizedAyah = normalizeArabic(ayah.text).lowercase()
                if (normalizedAyah.contains(normalizedQuery)) {
                    results.add(
                        AyahSearchResult(
                            surah = surah,
                            ayah = ayah,
                            matchedText = ayah.text
                        )
                    )
                }
            }
        }
        return results
    }

    private fun generateAyahsForSurah(surahNumber: Int): List<Ayah> {
        val surah = QuranDataProvider.surahs.find { it.number == surahNumber } ?: return emptyList()
        val ayahs = mutableListOf<Ayah>()
        for (i in 1..surah.numberOfAyahs) {
            val sampleVerseText = authenticVersesFallback[surahNumber]?.getOrNull(i - 1)
                ?: "بِسْمِ اللَّهِ الرَّحْمَٰنِ الرَّحِيمِ"
            ayahs.add(
                Ayah(
                    number = surahNumber * 1000 + i,
                    numberInSurah = i,
                    surahNumber = surahNumber,
                    text = sampleVerseText,
                    juz = QuranPageMapper.getJuzForPage(surah.pageNumber + (i / 15)),
                    page = (surah.pageNumber + (i / 15)).coerceIn(1, 604),
                    tafsir = ""
                )
            )
        }
        return ayahs
    }

